// Regenerates data/lots.json (lots) and data/rules.v2026-fall.json from the DOTS
// permit catalog. Run: node scripts/import-dots.mjs [path-to-saved-data.json]
// Buildings in lots.json are left untouched (scripts/import-campus-map.mjs owns them).
import { readFile, writeFile } from "node:fs/promises";
import { buildFromCatalog } from "./dots.mjs";

const SOURCE = "https://wcip.ipo.rutgers.edu/data.json";
const root = new URL("../data/", import.meta.url);

const catalog = process.argv[2]
  ? JSON.parse(await readFile(process.argv[2], "utf8"))
  : await (await fetch(SOURCE, { headers: { "User-Agent": "ru-parksmart-import" } })).json();

const lotsFile = JSON.parse(await readFile(new URL("lots.json", root), "utf8"));
const manual = JSON.parse(await readFile(new URL("rules.manual.json", root), "utf8"));
const { lots, rules, permits } = buildFromCatalog(catalog, lotsFile.lots);

const today = new Date().toISOString().slice(0, 10);
lotsFile._note =
  `Generated by scripts/import-dots.mjs from the DOTS permit catalog (${SOURCE}) on ${today}; ` +
  "coordinates may be refined by scripts/import-campus-map.mjs. coordsApprox lots have only 2-decimal coordinates in the catalog and are left out of trip planning. " +
  "CAPACITIES ARE ROUGH ESTIMATES (Rutgers does not publish them): they only turn team counts into a fill fraction, and /pilot lets the counter override them.";
const keepCoords = new Map(lotsFile.lots.filter((l) => l.coordsRefined).map((l) => [l.id, l]));
lotsFile.lots = lots.map((l) => (keepCoords.has(l.id) ? { ...l, center: keepCoords.get(l.id).center, coordsRefined: true, coordsApprox: undefined } : l));
await writeFile(new URL("lots.json", root), JSON.stringify(lotsFile, null, 2) + "\n");

const rulesFile = {
  version: "2026-fall",
  source:
    `Generated ${today} by scripts/import-dots.mjs from the DOTS permit catalog (${SOURCE}), plus data/rules.manual.json. ` +
    "Not yet confirmed with Rutgers Transportation Services. Fall 2026 NB permits are valid Aug 16, 2026 – Jan 16, 2027. " +
    "A permit id joined with '+' (primary + secondary) is allowed wherever either part is.",
  verified: false,
  verifiedOn: null,
  permits: [...permits, ...manual.permits],
  rules: [...rules, ...manual.rules],
};
await writeFile(new URL("rules.v2026-fall.json", root), JSON.stringify(rulesFile, null, 2) + "\n");

const byCampus = {};
for (const l of lotsFile.lots) byCampus[l.campus] = (byCampus[l.campus] ?? 0) + 1;
console.log("lots by campus:", byCampus);
console.log("approx coords:", lotsFile.lots.filter((l) => l.coordsApprox).map((l) => l.id).join(", ") || "none");
console.log(`rules: ${rulesFile.rules.length}, permits: ${rulesFile.permits.map((p) => p.id).join(", ")}`);
